/**
 * Global Search Query Matcher
 * Searches through all entities across title, subtitle, badge, status, and keywords.
 */
export function searchGlobalEntities(query) {
  const cleanQ = query.trim().toLowerCase();
  if (!cleanQ) return [];

  const terms = cleanQ.split(/\s+/).filter(Boolean);

  return GLOBAL_ENTITIES.filter((item) => {
    return terms.every((term) => {
      // Check title, subtitle, badge, category
      if (item.title.toLowerCase().includes(term)) return true;
      if (item.subtitle.toLowerCase().includes(term)) return true;
      if (item.badge.toLowerCase().includes(term)) return true;
      if (item.category.toLowerCase().includes(term)) return true;
      if (item.categoryLabel.toLowerCase().includes(term)) return true;
      if (item.statusLabel?.toLowerCase().includes(term)) return true;

      // Check keywords list
      if (item.keywords.some((kw) => kw.toLowerCase().includes(term))) return true;

      return false;
    });
  });
}

